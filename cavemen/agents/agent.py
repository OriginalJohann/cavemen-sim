"""Caveman agent with persistent profile.

Each agent carries vitals (HP, stamina, hunger), an aging system and a
persistent life-story profile (event log) that is saved together with the
world. Decisions come from the LLM (or deterministic fallback); this class
only holds state - all rule logic lives in simulation.rules.
"""


def age_years_of_ticks(cfg, ticks: float) -> float:
    """Convert sim-ticks to calendar years using the compressed time model."""
    per_year = max(1, int(cfg.get("simulation.ticks_per_day", 24))
                    * int(cfg.get("simulation.days_per_year", 36)))
    return ticks / per_year


class Agent:
    def __init__(self, uid: int, name: str, gender: str, x: int, y: int,
                 age_ticks: float = 0.0, prompt: str = ""):
        self.uid = int(uid)
        self.name = str(name)
        self.gender = gender                # 'm' or 'f'
        self.x, self.y = int(x), int(y)
        self.age_ticks = float(age_ticks)
        self.hp = 100.0                    # health points
        self.stamina = 80.0                # endurance; regenerated by rest
        self.hunger = 70.0                 # counts DOWN toward starvation
        self.alive = True
        self.death_cause = ""
        self.prompt = str(prompt)          # individual prompt, adapted over time
        self.story: list[tuple[int, str]] = []   # persistent life story (day, text)
        self.last_birth_tick = -10 ** 9    # last reproduction tick (cooldown)
        self.last_berry_gather_tick = -10 ** 9  # throttles "gathered berries" story events
        # Transient speech-bubble state; deliberately NOT serialized with saves:
        # bubbles are UI-only and expire after a few ticks.
        self.current_bubble = ""           # bubble text shown above the agent
        self.bubble_start_tick = -10 ** 9  # tick when current_bubble started
        self.next_decision_tick = 0        # when the agent next asks its LLM
        self.planned_action: dict = {"action": "rest", "dx": 0, "dy": 0}

    def age_years(self, cfg) -> float:
        return age_years_of_ticks(cfg, self.age_ticks)

    def is_child(self, cfg) -> bool:
        return self.age_years(cfg) < float(cfg.get("agents.age.child_until_years", 5))

    def is_elderly(self, cfg) -> bool:
        return self.age_years(cfg) >= float(cfg.get("agents.age.elderly_from_year", 40))

    def add_story(self, day: int, text: str) -> None:
        """Append a persistent life-story event (saved with the world)."""
        self.story.append((int(day), str(text)))

    def to_dict(self) -> dict:
        return {
            "uid": self.uid, "name": self.name, "gender": self.gender,
            "x": self.x, "y": self.y, "age_ticks": round(self.age_ticks, 3),
            "hp": round(self.hp, 2), "stamina": round(self.stamina, 2),
            "hunger": round(self.hunger, 2), "alive": self.alive,
            "death_cause": self.death_cause, "prompt": self.prompt,
            "story": [[d, t] for d, t in self.story],
            "last_birth_tick": self.last_birth_tick,
            "last_berry_gather_tick": int(self.last_berry_gather_tick),
        }

    @classmethod
    def from_dict(cls, data: dict, cfg) -> "Agent":
        agent = cls(data["uid"], data["name"], data["gender"], data["x"], data["y"],
                    float(data.get("age_ticks", 0.0)), str(data.get("prompt", "")))
        agent.hp = float(data.get("hp", 100.0))
        agent.stamina = float(data.get("stamina", 80.0))
        agent.hunger = float(data.get("hunger", 70.0))
        agent.alive = bool(data.get("alive", True))
        agent.death_cause = str(data.get("death_cause", ""))
        agent.story = [(int(d), str(t)) for d, t in data.get("story", [])]
        agent.last_birth_tick = int(data.get("last_birth_tick", -10 ** 9))
        agent.last_berry_gather_tick = int(data.get("last_berry_gather_tick", -10 ** 9))
        return agent
